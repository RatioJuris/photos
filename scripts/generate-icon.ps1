# ---------------------------------------------------------------- raster rendering (same geometry)
function Color($hex) { [System.Drawing.ColorTranslator]::FromHtml("#" + $hex.Substring(3)) | ForEach-Object { [System.Drawing.Color]::FromArgb([Convert]::ToInt32($hex.Substring(1, 2), 16), $_) } }

function New-PetalPath() {
    # Same path as $petal; quadratic segments converted to cubic Beziers.
    $p = New-Object System.Drawing.Drawing2D.GraphicsPath
    function Q($p0, $c, $p1) { @($p0, [System.Drawing.PointF]::new($p0.X + 2/3*($c.X-$p0.X), $p0.Y + 2/3*($c.Y-$p0.Y)), [System.Drawing.PointF]::new($p1.X + 2/3*($c.X-$p1.X), $p1.Y + 2/3*($c.Y-$p1.Y)), $p1) }
    function P($x, $y) { [System.Drawing.PointF]::new($x, $y) }
    $p.AddBezier((P 0 -6), (P -4.5 -8), (P -10.5 -15), (P -10 -23))
    foreach ($seg in @(@((P -10 -23), (P -9.2 -28.6), (P -5.4 -28)), @((P -5.4 -28), (P -3 -31.6), (P 0 -29.6)), @((P 0 -29.6), (P 3 -31.6), (P 5.4 -28)), @((P 5.4 -28), (P 9.2 -28.6), (P 10 -23)))) {
        $c = Q $seg[0] $seg[1] $seg[2]; $p.AddBezier($c[0], $c[1], $c[2], $c[3])
    }
    $p.AddBezier((P 10 -23), (P 10.5 -15), (P 4.5 -8), (P 0 -6))
    $p.CloseFigure()
    return $p
}

# Draws the bloom with its centre at (cx, cy); 1 vector unit = $unit pixels.
function Draw-Bloom($g, [float]$cx, [float]$cy, [float]$unit) {
    $petalPath = New-PetalPath
    for ($i = 0; $i -lt 6; $i++) {
        $state = $g.Save()
        $g.TranslateTransform($cx, $cy); $g.RotateTransform($angles[$i]); $g.ScaleTransform($unit, $unit)
        $g.FillPath((New-Object System.Drawing.SolidBrush (Color $colors[$i])), $petalPath)
        $pen = New-Object System.Drawing.Pen ((Color "#59FFFFFF"), 1.1); $pen.StartCap = 'Round'; $pen.EndCap = 'Round'
        $g.DrawLine($pen, 0, -10, 0, -24)
        $g.Restore($state)
    }
    $g.FillEllipse((New-Object System.Drawing.SolidBrush (Color "#FFB34700")), $cx - 3.6*$unit, $cy - 3.6*$unit, 7.2*$unit, 7.2*$unit)
    $g.FillEllipse((New-Object System.Drawing.SolidBrush (Color "#FFFFC21A")), $cx - 1.3*$unit, $cy - 1.3*$unit, 2.6*$unit, 2.6*$unit)
}

function New-RoundedRect([float]$x, [float]$y, [float]$w, [float]$h, [float]$r) {
    $p = New-Object System.Drawing.Drawing2D.GraphicsPath
    $d = 2 * $r
    $p.AddArc($x, $y, $d, $d, 180, 90); $p.AddArc($x + $w - $d, $y, $d, $d, 270, 90)
    $p.AddArc($x + $w - $d, $y + $h - $d, $d, $d, 0, 90); $p.AddArc($x, $y + $h - $d, $d, $d, 90, 90)
    $p.CloseFigure(); return $p
}

# Renders at 4x and downsamples for clean anti-aliasing at small sizes.
function Render-Icon([int]$size, [string]$shape, [string]$file) {
    $ss = 4; $n = $size * $ss
    $big = New-Object System.Drawing.Bitmap $n, $n, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($big)
    $g.SmoothingMode = 'AntiAlias'; $g.PixelOffsetMode = 'HighQuality'; $g.Clear([System.Drawing.Color]::Transparent)
    switch ($shape) {
        "square" {   # legacy icon: white rounded square with a hairline edge (Material legacy keyline: 44/48 dp)
            $inset = $n * 2 / 48; $side = $n - 2 * $inset
            $tile = New-RoundedRect $inset $inset $side $side ($side * 0.2)
            $g.FillPath([System.Drawing.Brushes]::White, $tile)
            $g.DrawPath((New-Object System.Drawing.Pen ((Color "#1F000000"), [float]($n / 192))), $tile)
            Draw-Bloom $g ($n / 2) ($n / 2) ($side / 72)
        }
        "round" {    # legacy round icon
            $inset = $n * 2 / 48; $d = $n - 2 * $inset
            $g.FillEllipse([System.Drawing.Brushes]::White, $inset, $inset, $d, $d)
            $g.DrawEllipse((New-Object System.Drawing.Pen ((Color "#1F000000"), [float]($n / 192))), $inset, $inset, $d, $d)
            Draw-Bloom $g ($n / 2) ($n / 2) ($d / 76)
        }
        "store" {    # Play Store: full-bleed square; Google Play applies its own mask and shadow
            $g.Clear([System.Drawing.Color]::White)
            Draw-Bloom $g ($n / 2) ($n / 2) ($n / 108)
        }
    }
    $g.Dispose()
    $out = New-Object System.Drawing.Bitmap $size, $size, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g2 = [System.Drawing.Graphics]::FromImage($out)
    $g2.InterpolationMode = 'HighQualityBicubic'; $g2.PixelOffsetMode = 'HighQuality'; $g2.SmoothingMode = 'AntiAlias'
    $g2.DrawImage($big, 0, 0, $size, $size); $g2.Dispose(); $big.Dispose()
    New-Item -ItemType Directory -Force (Split-Path $file) | Out-Null
    $out.Save($file, [System.Drawing.Imaging.ImageFormat]::Png); $out.Dispose()
}

$densities = [ordered]@{ "mdpi" = 48; "hdpi" = 72; "xhdpi" = 96; "xxhdpi" = 144; "xxxhdpi" = 192 }
foreach ($d in $densities.Keys) {
    Render-Icon $densities[$d] "square" (Join-Path $res "mipmap-$d\ic_launcher.png")
    Render-Icon $densities[$d] "round" (Join-Path $res "mipmap-$d\ic_launcher_round.png")
}
Render-Icon 512 "store" (Join-Path $main "ic_launcher-playstore.png")
Write-Host "Generated adaptive, monochrome, legacy (5 densities x 2 shapes) and Play Store icons."
