# Generates every Photos launcher asset from one geometry: six separate Indian Marigold
# (Tagetes erecta) petals with frilled tips, in warm marigold tones, around a small seed centre,
# on a white tile. Original artwork drawn from first principles; petals do not overlap, are not
# translucent and use only warm hues (deliberately unlike other photo-app marks).
#
# Outputs (app/src/main/...):
#   res/drawable/ic_launcher_foreground.xml   adaptive foreground (Android 8+), 108dp, safe-zone sized
#   res/drawable/ic_launcher_monochrome.xml   themed-icon layer (Android 13+)
#   res/mipmap-anydpi/ic_launcher(.xml|_round.xml)
#   res/mipmap-{m,h,xh,xxh,xxxh}dpi/ic_launcher.png, ic_launcher_round.png   legacy launchers
#   ic_launcher-playstore.png                 512 x 512 store listing icon

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Drawing
$main = Resolve-Path (Join-Path $PSScriptRoot "..\app\src\main")
$res = Join-Path $main "res"
$inv = [System.Globalization.CultureInfo]::InvariantCulture
$utf8 = New-Object System.Text.UTF8Encoding $false

# ---------------------------------------------------------------- geometry (108-unit viewport, centre 54,54)
$petal = "M0,-6 C-4.5,-8 -10.5,-15 -10,-23 Q-9.2,-28.6 -5.4,-28 Q-3,-31.6 0,-29.6 Q3,-31.6 5.4,-28 Q9.2,-28.6 10,-23 C10.5,-15 4.5,-8 0,-6 Z"
$vein = "M0,-10 L0,-24"
$colors = @("#FFFFC21A", "#FFFFA800", "#FFFF8F00", "#FFFF7600", "#FFF45D00", "#FFFFB000")
$angles = 0..5 | ForEach-Object { $_ * 60 + 30 }

# ---------------------------------------------------------------- vector drawables
function Write-Vector($file, [bool]$mono) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
    [void]$sb.AppendLine('<!-- Logo / app icon artwork. Copyright (C) 2026 Isrgrajan Gonardiya. SPDX-License-Identifier: GPL-3.0-or-later -->')
    [void]$sb.AppendLine('<!-- Original Indian Marigold petal artwork. Generated by scripts/generate-icon.ps1; do not edit by hand. -->')
    [void]$sb.AppendLine('<vector xmlns:android="http://schemas.android.com/apk/res/android"')
    [void]$sb.AppendLine('    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">')
    for ($i = 0; $i -lt 6; $i++) {
        $fill = if ($mono) { "#FFFFFFFF" } else { $colors[$i] }
        [void]$sb.AppendLine("    <group android:translateX=`"54`" android:translateY=`"54`" android:rotation=`"$($angles[$i])`">")
        [void]$sb.AppendLine("        <path android:fillColor=`"$fill`" android:pathData=`"$petal`" />")
        if (-not $mono) { [void]$sb.AppendLine("        <path android:strokeColor=`"#59FFFFFF`" android:strokeWidth=`"1.1`" android:strokeLineCap=`"round`" android:pathData=`"$vein`" />") }
        [void]$sb.AppendLine("    </group>")
    }
    if ($mono) {
        [void]$sb.AppendLine('    <path android:fillColor="#FFFFFFFF" android:pathData="M54,54 m-3.6,0 a3.6,3.6 0 1,0 7.2,0 a3.6,3.6 0 1,0 -7.2,0" />')
    } else {
        [void]$sb.AppendLine('    <path android:fillColor="#FFB34700" android:pathData="M54,54 m-3.6,0 a3.6,3.6 0 1,0 7.2,0 a3.6,3.6 0 1,0 -7.2,0" />')
        [void]$sb.AppendLine('    <path android:fillColor="#FFFFC21A" android:pathData="M54,54 m-1.3,0 a1.3,1.3 0 1,0 2.6,0 a1.3,1.3 0 1,0 -2.6,0" />')
    }
    [void]$sb.AppendLine('</vector>')
    [IO.File]::WriteAllText($file, $sb.ToString(), $utf8)
}
Write-Vector (Join-Path $res "drawable\ic_launcher_foreground.xml") $false
Write-Vector (Join-Path $res "drawable\ic_launcher_monochrome.xml") $true

